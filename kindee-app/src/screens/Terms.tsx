export function Terms({ onBack, initialTab = 'terms' }: { onBack: () => void; initialTab?: LegalTab }) {
  const [tab, setTab] = useState<LegalTab>(initialTab)
  const doc = DOC[tab]
  return (
    <div className="kd-screen">
      <div style={{ paddingTop: 'var(--safe-top)' }}>
        <Header title="ข้อกำหนดและความเป็นส่วนตัว" onBack={onBack} />
        <div className="kd-row" style={{ gap: 6, padding: '0 16px 12px' }}>
          {(['terms', 'privacy'] as const).map((value) => (
            <button key={value} className={`kd-chip${tab === value ? ' on' : ''}`} style={{ flex: 1, borderRadius: 12 }} aria-pressed={tab === value} onClick={() => setTab(value)}>
              {value === 'terms' ? 'เงื่อนไขการใช้งาน' : 'ประกาศความเป็นส่วนตัว'}
            </button>
          ))}
        </div>
      </div>
      <div className="kd-scroll" style={{ padding: '0 16px 32px' }}>
        <p className="kd-caption kd-muted">{doc.updated}</p>
        <div style={{ background: 'var(--accent-tint-soft)', border: '1px solid #d2cefd', borderRadius: 'var(--r-card)', padding: 14, margin: '12px 0 20px' }}>
          <div className="kd-label" style={{ fontWeight: 500, marginBottom: 6 }}>สรุปสั้น ๆ</div>
          <ul style={{ margin: 0, paddingLeft: 18, display: 'grid', gap: 4 }}>
            {doc.summary.map((item) => <li key={item} className="kd-body" style={{ color: 'var(--text-body-alt)' }}>{item}</li>)}
          </ul>
        </div>
        <div style={{ display: 'grid', gap: 20 }}>
          {doc.sections.map(([title, body]) => (
            <section key={title}>
              <h2 style={{ fontSize: 15.5, fontWeight: 500, lineHeight: 1.4, marginBottom: 6 }}>{title}</h2>
              <p style={{ fontSize: 13.5, lineHeight: 1.75, color: 'var(--text-body-alt)' }}>{body}</p>
            </section>
          ))}
        </div>
        <p className="kd-caption kd-muted" style={{ marginTop: 24 }}>
          ติดต่อผู้ควบคุมข้อมูล: <a href={`mailto:${legalConfig.privacyEmail}`}>{legalConfig.privacyEmail}</a>
        </p>
      </div>
    </div>
  )
}
