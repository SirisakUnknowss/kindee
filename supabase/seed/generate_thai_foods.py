def add(name, cat, grams, kcal, p, c, f, *, dish=True, portion='จาน', en=None, pop=50, aliases=()):
    if name in seen:
        return
    seen.add(name)
    rows.append(dict(name=name, cat=cat, grams=round(grams), kcal=kcal, p=p, c=c, f=f,
                     dish=dish, portion=portion, en=en, pop=pop, aliases=list(aliases)))


def combo(*parts, scale=1.0):
    g = k = p = c = f = 0.0
    for part in parts:
        pg, pk, pp, pc, pf = part
        g += pg; k += pk; p += pp; c += pc; f += pf
    return g * scale, k * scale, p * scale, c * scale, f * scale


def add_combo(name, cat, parts, **kw):
    add(name, cat, *combo(*parts, scale=kw.pop('scale', 1.0)), **kw)


