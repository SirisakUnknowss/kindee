def drink_group(base, items, *, pop=35):
    """Variants of one base drink: (name, +kcal, +carb[, +fat]) relative to base=(g, kcal, p, c, f)."""
    g, bk, bp, bc, bf = base
    for item in items:
        name, dk, dc = item[0], item[1], item[2]
        df = item[3] if len(item) > 3 else 0
        add(name, 'drink', g, bk + dk, bp, round(bc + dc, 1), round(bf + df, 1), portion='แก้ว', pop=pop)


