# ── SQL output ───────────────────────────────────────────────
def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def arr(items):
    return "array[" + ",".join(q(x) for x in items) + "]::text[]" if items else "'{}'::text[]"


def per100(v, g):
    return round(v * 100 / g, 2) if g else 0


def names_in_migration(path: str) -> set[str]:
    """Names already inserted by an earlier generated seed migration."""
    import re
    text = open(path, encoding='utf-8').read()
    return set(re.findall(r"\('seed:th:\d+', '((?:[^']|'')*)'", text))


def main(limit: int | None = None, since: list[str] | None = None):
    items = sorted(rows, key=lambda r: -r['pop'])
    if limit:
        items = items[:limit]
    if since:
        existing = {name.replace("''", "'") for path in since for name in names_in_migration(path)}
        items = [r for r in items if r['name'] not in existing]
    out = sys.stdout
    out.write('-- Generated by supabase/seed/generate_thai_foods.py — do not edit by hand.\n')
    out.write(f'-- {len(items)} curated Thai foods (estimates per typical serving, quality=community).\n\n')
    out.write('create temporary table _seed_foods (\n  seed_id text, name_th text, name_en text, aliases text[], category text,\n'
              '  is_dish boolean, kcal_100g numeric, protein_100g numeric, carb_100g numeric, fat_100g numeric,\n'
              '  serving_size_g numeric, portion_label text, popularity int\n);\n\n')
    for i in range(0, len(items), 200):
        out.write('insert into _seed_foods values\n')
        chunk = items[i:i + 200]
        for j, r in enumerate(chunk):
            g = r['grams']
            out.write('  (' + ', '.join([
                q(f"seed:th:{i + j + 1:04d}"), q(r['name']), 'null', arr(r['aliases']), q(r['cat']),
                'true' if r['dish'] else 'false', str(per100(r['kcal'], g)), str(per100(r['p'], g)),
                str(per100(r['c'], g)), str(per100(r['f'], g)), str(g), q(r['portion']), str(r['pop']),
            ]) + (')\n' if j == len(chunk) - 1 else '),\n'))
        out.write(';\n\n')
    # Removing foods the generator no longer produces is only safe when this
    # file holds the complete set; a --since delta would delete everything else.
    cleanup = '' if since else '''-- Seeded names that the generator no longer produces (e.g. the old doubled
-- "แกงไตปลาปลา"). Entries keep their own name and kcal; food_id becomes null.
delete from public.foods f
where f.source = 'curated' and f.source_id like 'seed:th:%'
  and not exists (select 1 from _seed_foods s where md5(s.name_th)::uuid = f.id);

'''
    out.write('''insert into public.foods (id, name_th, name_en, aliases, category, is_dish, is_packaged,
  kcal_100g, protein_100g, carb_100g, fat_100g, serving_size_g, source, source_id,
  quality, region, is_public, search_text, popularity)
select md5(s.name_th)::uuid, s.name_th, s.name_en, s.aliases, s.category, s.is_dish, false,
  s.kcal_100g, s.protein_100g, s.carb_100g, s.fat_100g, s.serving_size_g, 'curated', s.seed_id,
  'community', 'TH', true,
  public.normalize_thai(s.name_th || ' ' || array_to_string(s.aliases, ' ')), s.popularity
from _seed_foods s
on conflict (id) do update set
  aliases = excluded.aliases, category = excluded.category, is_dish = excluded.is_dish,
  kcal_100g = excluded.kcal_100g, protein_100g = excluded.protein_100g, carb_100g = excluded.carb_100g,
  fat_100g = excluded.fat_100g, serving_size_g = excluded.serving_size_g, source_id = excluded.source_id,
  search_text = excluded.search_text, popularity = excluded.popularity;

insert into public.food_portions (id, food_id, label_th, grams, is_default, sort_order)
select md5('portion:' || s.name_th)::uuid, md5(s.name_th)::uuid, s.portion_label, s.serving_size_g, true, 0
from _seed_foods s
on conflict (id) do update set label_th = excluded.label_th, grams = excluded.grams;


''' + cleanup + '''drop table _seed_foods;
''')


